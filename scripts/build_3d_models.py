#!/usr/bin/env python3
"""Build Cleaver's local visualization models (optional FreeCAD dependency).

Normal KiCad regeneration uses the committed models and does not need FreeCAD.
See kicad/Cleaver.3dshapes/README.md for licenses, sources, and limitations.
"""
from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

from design import ROOT


def freecad():
    try:
        import FreeCAD
    except ImportError:
        # Arch Linux's FreeCAD Python modules are not on Python's default path.
        path = Path('/usr/lib/freecad/lib')
        if path.is_dir():
            sys.path.append(str(path))
        import FreeCAD
    import Part
    return FreeCAD, Part


def export_model(name, pieces, folder, note):
    """STEP for CAD export, colored VRML for the viewer, all geometry in mm."""
    _, part = freecad()
    shapes = [shape for _, shape, _ in pieces]
    assert all(not shape.isNull() and shape.isValid() for shape in shapes), name
    compound = part.makeCompound(shapes)
    compound.exportStep(str(folder/(name+'.step')))
    lines = ['#VRML V2.0 utf8', '# '+note,
             '# Generated by scripts/build_3d_models.py; coordinates in 0.1 inch (KiCad VRML convention).']
    for label, shape, color in pieces:
        vertices, triangles = shape.tessellate(.025)
        points = ',\n'.join('        '+' '.join(f'{v/2.54:.7f}' for v in vertex) for vertex in vertices)
        faces = ',\n'.join('        '+', '.join(str(i) for i in triangle)+', -1' for triangle in triangles)
        lines.extend([
            '# '+label,
            'Shape {',
            '  appearance Appearance { material Material {',
            '    diffuseColor '+' '.join(str(c) for c in color),
            '    specularColor 0.22 0.22 0.22',
            '    shininess 0.35',
            '  } }',
            '  geometry IndexedFaceSet {',
            '    creaseAngle 0.6',
            '    coord Coordinate { point [', points, '    ] }',
            '    coordIndex [', faces, '    ]',
            '  }',
            '}',
        ])
    (folder/(name+'.wrl')).write_text('\n'.join(lines)+'\n')
    box = compound.BoundBox
    return dict(bounds_mm=[round(v, 5) for v in (box.XMin, box.YMin, box.ZMin,
                                                box.XMax, box.YMax, box.ZMax)],
                solids=len(compound.Solids), description=note)


def controller():
    """Visual envelope only: not a manufacturer-qualified YD assembly model."""
    app, part = freecad()
    pieces = []
    black, metal, gold = (.045,.05,.055), (.72,.74,.76), (.83,.65,.24)
    pcb_bottom, pcb_top = 2.54, 4.14

    def box(label, x, y, z, dx, dy, dz, color):
        shape = part.makeBox(dx,dy,dz,app.Vector(x,y,z))
        pieces.append((label,shape,color))
        return shape

    pcb = part.makeBox(22.86,53.34,1.6,app.Vector(-11.43,-26.67,pcb_bottom))
    for x in (-8.89,8.89):
        # Direct-soldered male headers, NOT an assertion about optional sockets.
        box('Header insulator',x-1.27,-25.4,0,2.54,50.8,2.54,black)
        for i in range(20):
            y = 24.13-2.54*i
            hole = part.makeCylinder(.5,1.6,app.Vector(x,y,pcb_bottom))
            pcb = pcb.cut(hole)
            ring = part.makeCylinder(.9,.04,app.Vector(x,y,pcb_top)).cut(
                part.makeCylinder(.5,.04,app.Vector(x,y,pcb_top)))
            pieces.append(('Module header annulus',ring,gold))
            box('Header pin',x-.32,y-.32,-2.7,.64,.64,7.6,gold)
    pieces.append(('53.34 x 22.86 mm module PCB',pcb,black))
    box('RP2040 approximate package',-3.5,-5.5,pcb_top,7,7,1.1,black)
    for i in range(12):
        p = -3.05+i*.55
        for x in (-3.85,3.5):
            box('RP2040 lead',x,p-2.15,pcb_top+.08,.35,.22,.18,metal)
        for y in (-5.85,1.5):
            box('RP2040 lead',p-.11,y,pcb_top+.08,.22,.35,.18,metal)
    box('Flash approximate package',1,6,pcb_top,4,5,1.1,black)
    box('Crystal approximate package',-5.9,-12.5,pcb_top,2.7,3.4,.9,metal)
    for x,y in ((-5.5,-20),(5.5,-20),(-5.5,8)):
        box('Approximate button body',x-2,y-1.7,pcb_top,4,3.4,1.6,metal)
        pieces.append(('Button plunger',part.makeCylinder(1.05,.55,app.Vector(x,y,pcb_top+1.6)),black))
    box('Onboard RGB LED',-2.5,-22.5,pcb_top,5,5,1.3,(.85,.84,.75))
    pieces.append(('Onboard RGB lens',part.makeCylinder(1.75,.03,app.Vector(0,-20,pcb_top+1.3)),(.94,.93,.86)))
    for x,y in ((-5,3),(5,3),(-5,-9),(5,-9),(5,13),(-5,16)):
        box('Representative module passive',x-.5,y-.8,pcb_top,1,1.6,.5,(.47,.32,.18))
    # A hollow, rounded USB-C envelope. Supplier shell geometry is unverified.
    shell = part.makeBox(9,7.5,3.2,app.Vector(-4.5,19.9,pcb_top))
    edges = [e for e in shell.Edges if abs(e.Length-7.5)<1e-6]
    shell = shell.makeFillet(.65,edges)
    hole = part.makeBox(8.3,7.5,2.5,app.Vector(-4.15,20.2,pcb_top+.35))
    edges = [e for e in hole.Edges if abs(e.Length-7.5)<1e-6]
    hole = hole.makeFillet(.45,edges)
    pieces.append(('Approximate USB-C shell',shell.cut(hole),metal))
    box('USB-C tongue',-3.3,22.8,pcb_top+1.35,6.6,4,.5,black)
    return pieces


def capacitor():
    """8 mm diameter / 11.5 mm nominal body, 3.5 mm pin pitch; simplified."""
    app, part = freecad()
    origin = app.Vector(0,0,.3)
    can = part.makeCylinder(4,11.5,origin)
    top = part.makeCylinder(3.72,.04,app.Vector(0,0,11.8))
    # Negative stripe faces +X, the circular pad 2 on the carrier.
    stripe = part.makeCylinder(4.01,10.1,app.Vector(0,0,.8),app.Vector(0,0,1),55).cut(
        part.makeCylinder(3.96,10.1,app.Vector(0,0,.8)))
    stripe.rotate(app.Vector(),app.Vector(0,0,1),-27.5)
    vent = part.makeBox(5,.07,.04,app.Vector(-2.5,-.035,11.84)).fuse(
        part.makeBox(.07,5,.04,app.Vector(-.035,-2.5,11.84)))
    pieces = [('Nominal can envelope',can,(.055,.065,.075)),
              ('Negative stripe',stripe,(.76,.78,.8)),
              ('Aluminum top',top,(.7,.72,.74)),('Vent mark',vent,(.25,.27,.3))]
    for x in (-1.75,1.75):
        pieces.append(('Lead',part.makeCylinder(.3,2.8,app.Vector(x,0,-2.5)),(.7,.72,.74)))
    return pieces


def reverse_led(folder):
    app, part = freecad()
    original = part.read(str(folder/'LED_SK6812MINI-E.step'))
    pieces = []
    for i, solid in enumerate(original.Solids):
        shape = solid.copy()
        shape.rotate(app.Vector(),app.Vector(1,0,0),180)
        # Original model was drawn below a 1.6mm carrier at y=-5.08.
        # Normalize to the reverse-mount footprint's own solder-side origin.
        shape.translate(app.Vector(0,-5.08,-1.70))
        pieces.append(('Body' if i==0 else 'Lead',shape,
                       (.88,.87,.79) if i==0 else (.72,.74,.76)))
    return pieces


def export_keyswitch_sources(source_dir, folder):
    app, part = freecad()
    for name in ('SW_Cherry_MX_Plate','SW_Hotswap_Kailh_MX'):
        doc = app.openDocument(str(source_dir/(name+'.FCStd')))
        roots = [o for o in doc.RootObjects if o.TypeId=='App::Part']
        assert len(roots)==1, name
        # Root assembly Shape includes the child placements. Do not export
        # individual children in their unrelated local assembly coordinates.
        shape = roots[0].Shape
        assert shape.isValid()
        shape.exportStep(str(folder/(name+'.step')))
        app.closeDocument(doc.Name)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--keyswitch-sources',type=Path,
                        help='Optional directory containing the pinned KiSwitch FCStd sources')
    args = parser.parse_args()
    folder = ROOT/'kicad/Cleaver.3dshapes'
    results = {}
    for name,pieces,note in (
            ('YD_RP2040_Approx',controller(),
             'Simplified YD-RP2040 / direct male headers; visual approximation, not mechanical sign-off. CC0-1.0.'),
            ('C_Radial_D8_H11.5_P3.5',capacitor(),
             'Simplified nominal EEU-FR1A471 envelope, not a tolerance model. CC0-1.0.'),
            ('LED_SK6812MINI-E_Reverse',reverse_led(folder),
             'Adapted 2026-11-08 from ebastler/marbastlib: recentered and reverse-mount normalized; CERN-OHL-P-2.0.')):
        results[name] = export_model(name,pieces,folder,note)
    (folder/'generated.json').write_text(json.dumps(results,indent=2)+'\n')
    if args.keyswitch_sources:
        export_keyswitch_sources(args.keyswitch_sources,folder)
    print('Built',len(results),'local STEP/VRML pairs; optional KiSwitch STEP exports:',bool(args.keyswitch_sources))


if __name__=='__main__':
    main()
